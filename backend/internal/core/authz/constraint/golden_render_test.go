// The conformance suite for the constraint renderer.
//
// # Why a golden file rather than the table in render_test.go
//
// TestRenderSaysWhatTheUserIsSigning already pins sentences, and it is enough
// while Go is the only thing that renders one. It stopped being enough when a
// second implementation appeared: frontend/src/constraint/render.ts renders
// constraints in the Mandate Inspector, which decodes a mandate signed some time
// ago with no live surface to ask, and in the console, which shows what a prompt
// would authorise before anything is signed. Neither has a signature in it,
// which is what makes a TypeScript renderer legitimate at all — the consent path
// keeps asking the surface, because the sentence the user reads has to be the
// sentence the signature covers.
//
// Two renderers means the sentence is now an interoperable artefact rather than
// one package's output, and this file is what stops them drifting. Go owns
// contracts/testdata/render_vectors.json: the table below is the source, the
// file is generated from it, and TypeScript only reads. So a change to Render()
// with no regeneration fails here, in the language that made the change, rather
// than in a suite one directory tree away.
//
// AGENTS.md's rule for widening `make vectors` beyond adapters/ and pkg/ is
// "something in core/ that a second implementation has to reproduce". This is
// that thing, and the Makefile was widened to match.

// goldenPath is the vector file, relative to this package. `go test` runs with
// the package directory as its working directory, so this resolves the same way
// from `make`, from CI and from an editor.
const goldenPath = "../../../../../contracts/testdata/render_vectors.json"

// update rewrites the vector file from the table below.
//
//	go test ./internal/core/authz/constraint -run TestGoldenRenderVectors -update
//
// A flag rather than an environment variable so that it shows up in `go test
// -args -h` beside the toolchain's own, and so that a stray export cannot
// silently turn a comparison into a rewrite.
var update = flag.Bool("update", false, "rewrite the render vectors from the renderer")

// renderVector is one sentence, and the constraint that produces it.
type renderVector struct {
	// Name identifies the vector. The TypeScript suite names a handful of these
	// directly, so they are part of the file's contract rather than labels.
	Name string `json:"name"`

	// Note says what this vector is here to catch, where that is not obvious
	// from the sentence. Read by people, not by either suite.
	Note string `json:"note,omitempty"`

	// Constraint is the node as it arrives on a mandate.
	Constraint json.RawMessage `json:"constraint"`

	// Rendered is what Render() says about it. "an unparsed constraint" is the
	// answer for every node Parse refuses, which is not a placeholder: it is
	// what a caller gets from the zero Expression that Parse returns beside its
	// error, and what a surface handed one must print rather than crash.
	Rendered string `json:"rendered"`
}

// renderVectorFile is the whole document.
type renderVectorFile struct {
	Comment string         `json:"$comment"`
	Vectors []renderVector `json:"vectors"`
}

