// It exists for the failure message rather than for the comparison: two
// json.RawMessage values that differ print as a hex dump of both, and the
// difference between an indented constraint and the same constraint on one line
// fills a screen while saying nothing. Flattening also makes the comparison the
// right one — the table writes its constraints across several lines for reading
// and the file holds them indented, and neither is a fact about the renderer.
type vectorSummary struct {
	Name       string
	Note       string
	Constraint string
	Rendered   string
}

func summarise(t *testing.T, vs []renderVector) []vectorSummary {
	t.Helper()

	out := make([]vectorSummary, 0, len(vs))
	for _, v := range vs {
		var flat bytes.Buffer
		require.NoError(t, json.Compact(&flat, v.Constraint), "compacting the constraint of %s", v.Name)
		out = append(out, vectorSummary{
			Name:       v.Name,
			Note:       v.Note,
			Constraint: flat.String(),
			Rendered:   v.Rendered,
		})
	}
	return out
}

// TestGoldenRenderVectors is the whole of the cross-language contract: the file
// on disk must be what this renderer produces.
//
// It compares the decoded vectors first and the bytes second, because the two
// failures want different fixes. A sentence that changed is a decision about
// what a user reads, and the assertion prints which one; a byte difference with
// identical vectors is formatting, and only needs the file regenerating.
func TestGoldenRenderVectors(t *testing.T) {
	t.Parallel()

	want := render(t)

	if *update {
		require.NoError(t, os.WriteFile(goldenPath, encode(t, want), 0o644), "rewriting the vectors")
		t.Logf("wrote %d vectors to %s", len(want.Vectors), goldenPath)
		return
	}

	raw, err := os.ReadFile(goldenPath)
	require.NoError(t, err, "reading the vectors; run this test with -update to create the file")
	require.NotEmpty(t, raw, "the vector file is empty, which no comparison below would notice")

	var got renderVectorFile
	require.NoError(t, json.Unmarshal(raw, &got), "decoding the vectors")

	assert.Equal(t, summarise(t, want.Vectors), summarise(t, got.Vectors),
		"the sentences on disk are not the ones this renderer produces; if the change to Render was "+
			"intended, regenerate with -update and read the diff as a change to what a user is shown")
	assert.Equal(t, string(encode(t, want)), string(raw),
		"the file's formatting has drifted from what -update writes, which would make every "+
			"regeneration show a spurious diff")
}

// TestGoldenRenderVectorsCoverEveryOperator holds the file to the operator
// table.
//
// TestEveryOperatorCanSayItself already proves each operator produces a sentence
// with no gap in it. This proves the *cross-language* suite sees each one: an
// operator added to the table with a phrase, and no vector, would be rendered by
// Go and by nothing else, and the two implementations could disagree about it
// indefinitely.
//
// It reads the file rather than the table above, so deleting a vector from the
// file fails here as well as in the byte comparison — a suite over a file is
// only as good as the file.
func TestGoldenRenderVectorsCoverEveryOperator(t *testing.T) {
	t.Parallel()

	named := make(map[string]struct{})
	for _, v := range onDisk(t).Vectors {
		named[v.Name] = struct{}{}
	}

	for _, op := range constraint.OperatorNames() {
		_, ok := named["operator-"+op]
		assert.True(t, ok,
			"no vector named operator-%s; the operator renders in Go and is unchecked in every other implementation", op)
	}
}

// TestGoldenRenderVectorsRefuseWhatTheyClaimTo checks that the two halves of the
// table have not been mixed up.
//
// Every vector whose sentence is "an unparsed constraint" must be one Parse
// actually refuses, and every other vector must be one it accepts. Without this
// a constraint that quietly stopped parsing — a field renamed, an operand rule
// tightened — would regenerate to the fallback sentence and the file would
// still be self-consistent, having silently lost whatever the vector proved.
func TestGoldenRenderVectorsRefuseWhatTheyClaimTo(t *testing.T) {
	t.Parallel()

	for _, v := range onDisk(t).Vectors {
		t.Run(v.Name, func(t *testing.T) {
			t.Parallel()

			_, err := constraint.Parse(node(t, string(v.Constraint)))
			if v.Rendered == unparsed {
				assert.Error(t, err,
					"this vector says the constraint cannot be read, and Parse read it")
				return
			}
			assert.NoError(t, err,
				"this vector carries a sentence, so it has to be a constraint a verifier can read")
			assert.False(t, strings.Contains(v.Rendered, "  ") || strings.HasSuffix(v.Rendered, " "),
				"the sentence has a gap in it where a phrase should be: %q", v.Rendered)
		})
	}
}

// onDisk reads the vector file, and is where the read is proved rather than
// assumed: an empty or wrongly-rooted path would make the two tests above pass
// over nothing.
func onDisk(t *testing.T) renderVectorFile {
	t.Helper()

	raw, err := os.ReadFile(goldenPath)
	require.NoError(t, err, "reading the vectors from %s", goldenPath)

	var doc renderVectorFile
	require.NoError(t, json.Unmarshal(raw, &doc), "decoding the vectors")
	require.NotEmpty(t, doc.Vectors, "the vector file carries no vectors, and every check over it would pass")
	return doc
}
