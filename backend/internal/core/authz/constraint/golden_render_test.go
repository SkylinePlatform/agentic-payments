// nested builds a chain of `not` groups depth levels deep, ending in a leaf.
//
// The leaf is one of the levels, so nested(9) produces nodes at depths 0 to 8 —
// exactly MaxDepth — and nested(10) is the first one Parse refuses.
func nested(depth int) string {
	node := `{"op":"eq","field":"item.category","value":"flights"}`
	for i := 1; i < depth; i++ {
		node = `{"op":"not","of":[` + node + `]}`
	}
	return node
}

// render produces the file from the table.
func render(t *testing.T) renderVectorFile {
	t.Helper()

	out := renderVectorFile{Comment: fileComment, Vectors: make([]renderVector, 0, len(vectors))}
	seen := make(map[string]struct{}, len(vectors))

	for _, v := range vectors {
		_, duplicate := seen[v.name]
		require.False(t, duplicate, "two vectors are named %q; the TypeScript suite selects by name", v.name)
		seen[v.name] = struct{}{}

		// The error is deliberately dropped rather than checked here. Parse
		// returns the zero Expression beside it, and rendering that is exactly
		// what a surface handed an unreadable constraint does — so one code
		// path covers both halves of the table, and the assertion that the two
		// halves are not mixed up lives in TestGoldenRenderVectorsRefuseWhatTheyClaimTo.
		expression, _ := constraint.Parse(node(t, v.raw))

		out.Vectors = append(out.Vectors, renderVector{
			Name:       v.name,
			Note:       v.note,
			Constraint: json.RawMessage(v.raw),
			Rendered:   expression.Render(),
		})
	}
	return out
}

// encode is the file's exact bytes. MarshalIndent re-indents the raw constraint
// bodies too, so the table may hold them formatted for reading.
func encode(t *testing.T, doc renderVectorFile) []byte {
	t.Helper()

	out, err := json.MarshalIndent(doc, "", "  ")
	require.NoError(t, err, "encoding the vectors")
	return append(out, '\n')
}

